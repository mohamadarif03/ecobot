/**
 * Dev-only validator to ensure no card exceeds 40 words (PRD 6.4)
 */
export function validatePustakaCardWordCounts(): { passed: boolean; violations: { topic: string; cardId: string; wordCount: number }[] } {
  const violations: { topic: string; cardId: string; wordCount: number }[] = [];

  PUSTAKA_TOPICS.forEach((topic) => {
    topic.kartu.forEach((card) => {
      const words = card.isi.trim().split(/\s+/).filter(Boolean);
      if (words.length > 40) {
        violations.push({
          topic: topic.slug,
          cardId: card.id,
          wordCount: words.length,
        });
      }
    });
  });

  return {
    passed: violations.length === 0,
    violations,
  };
}
